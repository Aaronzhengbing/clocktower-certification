const fs = require('fs');
const path = require('path');

const QUESTIONS_FILE = path.join(__dirname, '..', 'data', 'questions.json');

// 加载现有题目
let existingData;
try {
  existingData = JSON.parse(fs.readFileSync(QUESTIONS_FILE, 'utf-8'));
} catch (e) {
  console.error('无法读取现有题库:', e.message);
  process.exit(1);
}

const existingIds = new Set(existingData.questions.map(q => q.id));
const nextId = Math.max(...existingIds) + 1;

// 生成新题目的函数
function genSingle(id, category, difficulty, question, options, answer, explanation, tags) {
  return { id, type: 'single', category, difficulty, question, options, answer, explanation, tags };
}

function genJudge(id, category, difficulty, question, answer, explanation, tags) {
  return {
    id, type: 'judge', category, difficulty,
    question,
    options: ['是', '否'],
    answer: answer ? 'true' : 'false',
    explanation, tags
  };
}

